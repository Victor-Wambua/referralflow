<?php

namespace App\Domain;

use App\Models\DataRequest;
use App\Models\Message;
use App\Models\Patient;
use App\Models\Referral;
use App\Models\User;
use App\Security\AuditLog;
use App\Security\TenantContext;
use Illuminate\Auth\Access\AuthorizationException;

/**
 * Data-subject export and deletion workflow, per facility. A facility admin decides (with re-authentication).
 * Deletion is refused while a legal hold or an open referral exists. Legal retention duties may override
 * erasure: confirm with counsel.
 */
final class DataRequestService
{
    public static function open(User $u, Patient $patient, string $type): DataRequest
    {
        if (! $u->isClinical() || $patient->facility_id !== $u->facility_id || ! in_array($type, ['export', 'deletion'], true)) {
            throw new AuthorizationException('Cannot open this request.');
        }
        $r = DataRequest::query()->create([
            'facility_id' => $u->facility_id, 'patient_id' => $patient->id, 'type' => $type,
            'requested_by' => $u->id, 'status' => 'open', 'due_at' => now()->addDays(30),
        ]);
        AuditLog::record('data_request.open', 'data_request', $r->id, ['type' => $type]);

        return $r;
    }

    public static function reject(User $admin, DataRequest $req, string $note): DataRequest
    {
        self::guardAdmin($admin, $req);
        $req->forceFill(['status' => 'rejected', 'decided_by' => $admin->id, 'decided_at' => now(), 'decision_note' => $note])->save();
        AuditLog::record('data_request.reject', 'data_request', $req->id, [], $note);

        return $req;
    }

    /** @return array{0:DataRequest,1:?array} request and (for exports) the data package, released once */
    public static function approve(User $admin, DataRequest $req, ?string $note = null): array
    {
        self::guardAdmin($admin, $req);
        $patientId = $req->patient_id;
        if ($req->type === 'deletion') {
            $open = TenantContext::asSystem(fn () => Referral::query()->where('patient_id', $patientId)->whereNotIn('status', ['completed', 'declined', 'cancelled'])->exists());
            if (RetentionService::held(null, $patientId) || TenantContext::asSystem(fn () => Referral::query()->where('patient_id', $patientId)->get()->contains(fn ($r) => RetentionService::held($r->id, null)))) {
                return [self::block($admin, $req, 'A legal hold applies. Deletion cannot proceed.'), null];
            }
            if ($open) {
                return [self::block($admin, $req, 'Open referrals exist for this patient. Close or cancel them first.'), null];
            }
            TenantContext::asSystem(function () use ($patientId) {
                foreach (Referral::query()->where('patient_id', $patientId)->get() as $r) {
                    RetentionService::anonymiseReferral($r);
                }
                Patient::query()->withoutGlobalScopes()->whereKey($patientId)->delete();
            });
            $req->forceFill(['status' => 'completed', 'decided_by' => $admin->id, 'decided_at' => now(), 'completed_at' => now(), 'decision_note' => $note])->save();
            AuditLog::record('data_request.delete_done', 'data_request', $req->id, [], $note, 'data_request');

            return [$req, null];
        }

        $package = TenantContext::asSystem(fn () => self::package($patientId));
        $req->forceFill(['status' => 'completed', 'decided_by' => $admin->id, 'decided_at' => now(), 'completed_at' => now(), 'decision_note' => $note])->save();
        AuditLog::record('data_request.export_done', 'data_request', $req->id, ['referrals' => count($package['referrals'])], $note, 'data_request');

        return [$req, $package];
    }

    private static function package(int $patientId): array
    {
        $p = Patient::query()->withoutGlobalScopes()->findOrFail($patientId);

        return [
            'notice' => 'Synthetic demonstration data. Export generated by ReferralFlow for a data-subject request.',
            'patient' => ['name' => $p->full_name, 'date_of_birth' => $p->date_of_birth, 'sex' => $p->sex, 'identifier_type' => $p->identifier_type, 'identifier' => $p->identifier],
            'referrals' => Referral::query()->where('patient_id', $patientId)->get()->map(fn ($r) => [
                'id' => $r->id, 'status' => $r->status, 'priority' => $r->priority, 'reason_code' => $r->reason_code,
                'reason_text' => $r->reason_text, 'clinical_note' => $r->clinical_note, 'sent_at' => $r->sent_at?->toIso8601String(),
                'messages' => Message::query()->withoutGlobalScopes()->where('referral_id', $r->id)->get()->map(fn ($m) => ['at' => $m->created_at->toIso8601String(), 'body' => $m->body])->all(),
            ])->all(),
        ];
    }

    private static function block(User $admin, DataRequest $req, string $note): DataRequest
    {
        $req->forceFill(['status' => 'blocked', 'decided_by' => $admin->id, 'decided_at' => now(), 'decision_note' => $note])->save();
        AuditLog::record('data_request.blocked', 'data_request', $req->id, [], $note);

        return $req;
    }

    private static function guardAdmin(User $admin, DataRequest $req): void
    {
        if ($admin->role->value !== 'facility_admin' || $admin->facility_id !== $req->facility_id || $req->status !== 'open') {
            throw new AuthorizationException('Only the facility admin can decide an open request.');
        }
    }
}
